# In for loop we use range function range(start,stop,step_size)
for i in range(1,11):
    print(i)

# list using for() loop
l=[1,2,"shamshuddin","Hello"]
for i in l:
    print(i)

# tuple using for() loop
t=("APPLE","BANANA","ORANGE",)
for i in t:
    print(i)

# string using for() loop
s='shamshuddin'
for i in s:
    print(i)
